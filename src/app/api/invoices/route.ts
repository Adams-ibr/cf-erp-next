import { createResourceRoutes } from '@/lib/api/factory'
import { z } from 'zod'

const { GET, POST } = createResourceRoutes({
  tableName: 'invoices',
  createSchema: z.object({
    type: z.enum(['SALES', 'PURCHASE', 'CREDIT_NOTE', 'DEBIT_NOTE', 'PROFORMA', 'RECURRING', 'ADVANCE', 'DEPOSIT', 'FINAL', 'CORRECTION']).optional().default('SALES'),
    status: z.enum(['DRAFT', 'PENDING_APPROVAL', 'APPROVED', 'SENT', 'VIEWED', 'PARTIAL_PAID', 'PAID', 'OVERDUE', 'CANCELLED', 'REFUNDED', 'CREDIT_NOTE', 'DEBIT_NOTE', 'DISPUTED']).optional().default('DRAFT'),
    customer_id: z.string().uuid(),
    supplier_id: z.string().uuid().optional(),
    shipment_id: z.string().uuid().optional(),
    job_id: z.string().uuid().optional(),
    booking_id: z.string().uuid().optional(),
    currency: z.string().length(3).optional().default('USD'),
    exchange_rate: z.number().positive().optional().default(1),
    subtotal: z.number().min(0),
    tax_amount: z.number().min(0).default(0),
    discount_amount: z.number().min(0).default(0),
    total_amount: z.number().min(0),
    paid_amount: z.number().min(0).default(0),
    balance_amount: z.number().min(0),
    due_date: z.string().datetime(),
    issue_date: z.string().datetime(),
    billing_address: z.record(z.unknown()).optional(),
    shipping_address: z.record(z.unknown()).optional(),
    terms: z.string().optional(),
    notes: z.string().optional(),
    internal_notes: z.string().optional(),
    items: z.array(z.object({
      description: z.string(),
      quantity: z.number().positive(),
      unit: z.string(),
      unit_price: z.number().positive(),
      discount_percent: z.number().min(0).max(100).optional().default(0),
      discount_amount: z.number().min(0).optional().default(0),
      tax_percent: z.number().min(0).max(100).optional().default(0),
      tax_amount: z.number().min(0).optional().default(0),
      total_amount: z.number().positive(),
      commodity_code: z.string().optional(),
      weight: z.number().positive().optional(),
      volume: z.number().positive().optional(),
      origin: z.string().optional(),
      destination: z.string().optional(),
    })).min(1),
  }),
  updateSchema: z.object({
    type: z.enum(['SALES', 'PURCHASE', 'CREDIT_NOTE', 'DEBIT_NOTE', 'PROFORMA', 'RECURRING', 'ADVANCE', 'DEPOSIT', 'FINAL', 'CORRECTION']).optional(),
    status: z.enum(['DRAFT', 'PENDING_APPROVAL', 'APPROVED', 'SENT', 'VIEWED', 'PARTIAL_PAID', 'PAID', 'OVERDUE', 'CANCELLED', 'REFUNDED', 'CREDIT_NOTE', 'DEBIT_NOTE', 'DISPUTED']).optional(),
    customer_id: z.string().uuid().optional(),
    supplier_id: z.string().uuid().optional(),
    shipment_id: z.string().uuid().optional(),
    job_id: z.string().uuid().optional(),
    booking_id: z.string().uuid().optional(),
    currency: z.string().length(3).optional(),
    exchange_rate: z.number().positive().optional(),
    subtotal: z.number().min(0).optional(),
    tax_amount: z.number().min(0).optional(),
    discount_amount: z.number().min(0).optional(),
    total_amount: z.number().min(0).optional(),
    paid_amount: z.number().min(0).optional(),
    balance_amount: z.number().min(0).optional(),
    due_date: z.string().datetime().optional(),
    issue_date: z.string().datetime().optional(),
    billing_address: z.record(z.unknown()).optional(),
    shipping_address: z.record(z.unknown()).optional(),
    terms: z.string().optional(),
    notes: z.string().optional(),
    internal_notes: z.string().optional(),
  }),
})

export { GET, POST }